export function groupById(id: FeatureGroupId): FeatureGroup {
  return FEATURE_GROUPS.find((g) => g.id === id) ?? FEATURE_GROUPS[0]!;
}

/* ------------------------------------------------------------------------------------------------------ plan */

export type PlanTier = "frei" | "pro" | "premium" | "team";
export const PLAN_TIER_LABEL: Readonly<Record<PlanTier, string>> = { frei: "Frei", pro: "Pro", premium: "Premium", team: "Team" };
export const PLAN_TIERS: readonly PlanTier[] = ["frei", "pro", "premium", "team"];

/** The lowest plan whose feature set includes `gate` (`frei` without a gate or when the free plan has it). */
export function tierOf(gate: Feature | undefined): PlanTier {
  if (!gate) return "frei";
  const ids = (["free", "pro", "premium", "team"] as const).filter((p) => PLAN_FEATURES[p].has(gate)).sort((a, b) => PLAN_RANK[a] - PLAN_RANK[b]);
  const lowest = ids[0] ?? "team";
  return lowest === "free" ? "frei" : lowest;
}

/** Entries that really need a paid plan to use (not free). */
export const isPaidTier = (t: PlanTier): boolean => t !== "frei";
