/* ------------------------------------------------------------------------------------------------------- types */

export type FeatureGroupId = "heute" | "pruefen" | "risiko" | "testen" | "lernen" | "auswerten" | "wachsen" | "daten" | "community" | "konto";
export type FeatureStatus = "fertig" | "teilweise";
/** Sheets and dialogs that open over the current page (no navigation). */
export type FeatureAction = "training" | "assistant" | "newTrade" | "csvImport" | "shortcuts" | "shotImport" | "demo";
/** Where on the page: a `data-testid` of the page layer, else the start of a card heading (`h2` / `h3`). */
export interface FeatureAnchor {
  testid?: string;
  heading?: string;
}

export interface FeatureEntry {
  /** stable slug – deep link (`feature:<id>` in the search, recents), never renamed */
  id: string;
  /** Bauplan F-IDs this function (partly) implements; `[]` for functions outside the 74 points */
  fids: readonly string[];
  name: string;
  /** what you DO with it, in plain words and one short sentence ("Den Tag in vier Szenarien durchdenken"); the register test requires it */
  task?: string;
  /** one sentence: what it does for the trader */
  benefit: string;
  /** the ONE main group (a tile on the page "Funktionen"); other places point here with `see` */
  group: FeatureGroupId;
  /** sub heading inside the group's list – required once a group holds more than eight functions */
  sub?: string;
  /** the page it lives on (also the home of an `action`, for the register test) */
  page: Page;
  anchor?: FeatureAnchor;
  /** the section on the page in the page's own words ("Tagesplan", "Strategie & Kosten · Eigene Idee") – shown as "Markt › Tagesplan" */
  place?: string;
  action?: FeatureAction;
  /** how to get there when there is nothing to scroll to ("Trade öffnen → Was wäre wenn") */
  path?: string;
  keywords: readonly string[];
  /** how someone says it in their own words: synonyms and whole phrases ("warum verliere ich", "strategie testen"); the register test requires them */
  intents?: readonly string[];
  /** "Siehe auch": ids of related functions that live in another group or on another page */
  see?: readonly string[];
  /** month of the release that brought it (`2026-10`); "Neu" is shown for two months after it */
  since?: string;
  /** one of the few starting points offered as "Empfohlen" */
  star?: boolean;
  status: FeatureStatus;
  /** what is missing or limited – required for `teilweise`, optional limit for `fertig` */
  note?: string;
  /** plan feature behind it (`src/billing/plans.ts`); absent = free */
  gate?: Feature;
  /** device / browser hint (microphone, keyboard, downloads …) */
  device?: string;
  /** a precondition: why the anchor may be missing right now, or what the function needs ("Erscheint nach einem fertigen Lauf.", "Nur in der Cloud-Version mit Konto.") */
  needs?: string;
  /** assistant interest topics (`memory.ts`) that point here; `behavior:*` / `page:<page>` patterns allowed */
  topics?: readonly string[];
}

export interface FeatureGroup {
  id: FeatureGroupId;
  name: string;
  /** the one sentence under the tile */
  lead: string;
  icon: IconName;
}

