/**
 * Funktionsregister – die einzige Wahrheit darüber, WAS die App kann und WO es steht (Auffindbarkeit, kein Produktversprechen).
 *
 * Eine Zeile je Funktion: F-ID(s) des Bauplans, deutscher Name, ein Satz Nutzen, Gruppe (nach Aufgabe des Nutzers, nicht
 * nach Technik), Seite + Anker (oder ein Öffner), Stichwörter, Status und – ehrlich nach dem Code – was fehlt. Gelesen von:
 *   - der Seite „Funktionen“ (`src/views/funktionen`),
 *   - der globalen Suche (`src/search/sources.ts`, Art `feature`) und damit der Befehlsnavigation,
 *   - dem Assistenten („Wo finde ich …?“, `src/assistant/tools.ts`),
 *   - dem Abdeckungs-Dokument `docs/COVERAGE.md` (Test `tests/unit/features.registry.test.ts` hält beides zusammen).
 *
 * Rein: Daten und Funktionen ohne Seiteneffekte. Das Register bleibt in einem Lazy-Chunk (Funktionen-Seite, Suche,
 * Assistent) – die Erstladung importiert es nicht. Öffnen (navigieren, scrollen, Sheets) steht in `featureOpen.ts`.
 *
 * Regeln für neue Einträge:
 *   - nur, was im Code wirklich existiert; `status: "teilweise"` braucht eine `note`, die sagt, was fehlt;
 *   - ein Anker ist ein `data-testid` oder die Überschrift einer Karte der Seite – der Test prüft, dass der Text im Code steht;
 *   - was erst nach einer Aktion erscheint (ein Lauf, eine Gruppe) oder eine Voraussetzung hat (Cloud, Konto), trägt `needs` –
 *     das Öffnen sagt dann ehrlich, warum die Stelle fehlt, statt still oben zu bleiben;
 *   - eine F-ID mit Status „fehlt“ in `docs/COVERAGE.md` gehört NICHT ins Register.
 */
